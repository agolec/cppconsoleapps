#include <iostream>
#include <cstdlib>
using namespace std;
void battle();
void step();
int generateRandomNumber();

int main() {
	step();
	return 0;
}

/*
battle() will simulate a simple battle chain being counted within a game, similar to
Final Fantasy XII's battle chains, for the sake of making some simple demonstration that
is not exactly a coding challenge from the Tony Gaddis book.
*/
void battle() {
	static int battleChain = 1;

	cout << endl << endl << "Your current battle chain is : " << battleChain << endl << endl;
	battleChain++;
}
/*
	step() will simulate taking steps in a video game environment based on whatever
	number MAXIMUM_STEP_ITERATIONS is set to.

	If the number generated by GenerateRandomNumber() is even, or is greater than half of
	whatever number was given to it, it will call battle().
*/
void step() {
	const int MAXIMUM_STEP_ITERATIONS = 100;
	const int HALF_OF_MAX_STEP_ITERATIONS = MAXIMUM_STEP_ITERATIONS / 2;
	for (int i = 0; i < MAXIMUM_STEP_ITERATIONS; i++) {
		int randomNumber = generateRandomNumber();
		if (randomNumber % 2 == 0 || randomNumber > HALF_OF_MAX_STEP_ITERATIONS) {
			battle();
		}
		else {
			cout << i << ". No battle encountered this time..." << endl;
		}
	}
}
int generateRandomNumber() {
	return rand() % 101;
}